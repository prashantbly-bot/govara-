  /* =========================================================
     4. FRONTEND VALIDATION
     ========================================================= */

  function validate(data) {

    if (!data.name) {
      return {
        valid: false,
        error: 'Full Name is required.'
      };
    }

    if (data.name.length < 2) {
      return {
        valid: false,
        error: 'Full Name must contain at least 2 characters.'
      };
    }

    if (!data.mobile) {
      return {
        valid: false,
        error: 'Mobile number is required.'
      };
    }

    if (!/^[6-9][0-9]{9}$/.test(data.mobile)) {
      return {
        valid: false,
        error: 'Enter a valid Indian mobile number.'
      };
    }

    if (!data.email) {
      return {
        valid: false,
        error: 'Email is required.'
      };
    }

    if (
      !/^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$/i.test(
        data.email
      )
    ) {
      return {
        valid: false,
        error: 'Enter a valid email address.'
      };
    }

    if (!data.address) {
      return {
        valid: false,
        error: 'Address is required.'
      };
    }

    if (data.address.length > 500) {
      return {
        valid: false,
        error: 'Address cannot exceed 500 characters.'
      };
    }

    return {
      valid: true,
      data: data
    };
  }

  /* =========================================================
     5. REGISTRATION PAYLOAD
     ========================================================= */

  function buildRegistrationPayload() {

    var fields = getFields();

    /*
     * EXACT BACKEND CONTRACT
     *
     * GV_registerCustomer() expects:
     *
     * name
     * mobile
     * email
     * address
     *
     * No uppercase database column names.
     * No frontend-generated IDs.
     * No document IDs.
     */

    var payload = {
      name: fields.name,
      mobile: fields.mobile,
      email: fields.email,
      address: fields.address
    };

    console.log(
      '[GoVara Customer] CUSTOMER_REGISTER payload:',
      payload
    );

    return payload;
  }

  /* =========================================================
     6. API CALL
     ========================================================= */

  function callCustomerRegister(payload) {

    if (
      window.GoVaraAPI &&
      typeof window.GoVaraAPI.customerRegister === 'function'
    ) {
      return window.GoVaraAPI.customerRegister(payload);
    }

    if (
      window.GoVaraAPI &&
      typeof window.GoVaraAPI.request === 'function'
    ) {
      return window.GoVaraAPI.request({
        action: ACTION,
        module: MODULE,
        data: payload
      });
    }

    if (
      window.GoVara27 &&
      typeof window.GoVara27.customerRegister === 'function'
    ) {
      return window.GoVara27.customerRegister(payload);
    }

    throw new Error(
      'GoVara Consolidated API is not available.'
    );
  }

  /* =========================================================
     7. RESPONSE HANDLING
     ========================================================= */

  function handleResponse(response) {

    state.lastResponse = response;

    responseBox(response);

    if (!response) {
      message(
        'No response received from API.',
        'error'
      );
      return false;
    }

    /*
     * API-level failure
     */

    if (response.success !== true) {

      var errorText =
        response.error ||
        response.status ||
        (
          response.validation &&
          response.validation.errors
            ? response.validation.errors.join(', ')
            : ''
        ) ||
        'Customer registration failed.';

      message(
        errorText,
        'error'
      );

      return false;
    }

    /*
     * Business/service-level failure.
     *
     * Backend can return:
     *
     * success: true
     * result.success: false
     */

    var result = response.result || {};

    if (result.success === false) {

      var validationErrors =
        result.validation &&
        result.validation.errors
          ? result.validation.errors.join(', ')
          : '';

      var businessError =
        validationErrors ||
        result.error ||
        result.status ||
        'Customer registration failed.';

      message(
        businessError,
        'error'
      );

      return false;
    }

    /*
     * SUCCESS
     */

    var customerId =
      response.customerId ||
      result.customerId ||
      '';

    var userId =
      response.userId ||
      result.userId ||
      '';

    var status =
      response.status ||
      result.status ||
      'CUSTOMER_REGISTERED';

    if (el('customer-id')) {
      el('customer-id').textContent =
        customerId || '-';
    }

    if (el('customer-user-id')) {
      el('customer-user-id').textContent =
        userId || '-';
    }

    if (el('customer-registration-status')) {
      el('customer-registration-status').textContent =
        status;
    }

    var resultPanel =
      el('customer-registration-result');

    if (resultPanel) {
      resultPanel.style.display = 'block';
    }

    var successText =
      'Customer registered successfully.';

    if (customerId) {
      successText +=
        ' Customer ID: ' + customerId;
    }

    message(
      successText,
      'success'
    );

    return true;
  }

  /* =========================================================
     8. SUBMIT
     ========================================================= */

  async function submit() {

    if (state.submitting) {
      return;
    }

    var payload =
      buildRegistrationPayload();

    var validation =
      validate(payload);

    if (!validation.valid) {
      message(
        validation.error,
        'error'
      );
      return;
    }

    /*
     * Final safety check before API call.
     */

    if (
      !payload.name ||
      !payload.mobile ||
      !payload.email ||
      !payload.address
    ) {

      console.error(
        '[GoVara Customer] Empty registration payload:',
        payload
      );

      message(
        'Registration data is incomplete.',
        'error'
      );

      return;
    }

    state.submitting = true;

    var button =
      el('customer-register-btn');

    if (button) {
      button.disabled = true;
      button.textContent =
        'Registering...';
      button.style.opacity = '0.65';
      button.style.cursor = 'wait';
    }

    message(
      'Registering customer...',
      'info'
    );

    try {

      /*
       * IMPORTANT:
       * Send the exact payload directly.
       */

      var response =
        await Promise.resolve(
          callCustomerRegister(payload)
        );

      handleResponse(response);

    } catch (error) {

      console.error(
        '[GoVara Customer] Registration error:',
        error
      );

      message(
        String(
          error.message || error
        ),
        'error'
      );

    } finally {

      state.submitting = false;

      if (button) {
        button.disabled = false;
        button.textContent =
          'Register Customer';
        button.style.opacity = '1';
        button.style.cursor = 'pointer';
      }
    }
  }

  /* =========================================================
     9. PROFILE PHOTO PREVIEW
     ========================================================= */

  function bindPhoto() {

    var input =
      el('customer-profile-photo');

    if (!input) return;

    input.addEventListener(
      'change',
      function () {

        var file =
          input.files &&
          input.files.length
            ? input.files[0]
            : null;

        var preview =
          el('customer-photo-preview');

        var image =
          el('customer-photo-image');

        if (!file) {
          if (preview) {
            preview.style.display =
              'none';
          }
          return;
        }

        if (
          !file.type ||
          file.type.indexOf('image/') !== 0
        ) {

          input.value = '';

          message(
            'Please select a valid image file.',
            'error'
          );

          return;
        }

        var reader =
          new FileReader();

        reader.onload =
          function (event) {

            if (image) {
              image.src =
                event.target.result;
            }

            if (preview) {
              preview.style.display =
                'block';
            }
          };

        reader.readAsDataURL(file);
      }
    );
  }

  /* =========================================================
     10. INPUT FORMATTERS
     ========================================================= */

  function bindMobile() {

    var input =
      el('customer-mobile');

    if (!input) return;

    input.addEventListener(
      'input',
      function () {

        input.value =
          String(input.value || '')
            .replace(/[^0-9+]/g, '')
            .slice(0, 13);
      }
    );
  }

  function bindAadhaar() {

    var input =
      el('customer-aadhaar');

    if (!input) return;

    input.addEventListener(
      'input',
      function () {

        var value =
          String(input.value || '')
            .replace(/[^0-9]/g, '')
            .slice(0, 12);

        var parts =
          value.match(/.{1,4}/g);

        input.value =
          parts
            ? parts.join(' ')
            : '';
      }
    );
  }

  function bindPAN() {

    var input =
      el('customer-pan');

    if (!input) return;

    input.addEventListener(
      'input',
      function () {

        input.value =
          String(input.value || '')
            .toUpperCase()
            .replace(/[^A-Z0-9]/g, '')
            .slice(0, 10);
      }
    );
  }

  /* =========================================================
     11. BIND EVENTS
     ========================================================= */

  function bind() {

    var button =
      el('customer-register-btn');

    if (button) {
      button.addEventListener(
        'click',
        function (event) {
          event.preventDefault();
          submit();
        }
      );
    }

    bindPhoto();
    bindMobile();
    bindAadhaar();
    bindPAN();
  }

